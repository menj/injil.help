<h2 class="wp-block-heading">What this part shows</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The Qur’an refers to ʿĪsā ibn Maryam in ninety-three verses, more than to any prophet but Mūsā, and between them they speak to nearly every part of his story: his mother and his birth, his signs, his message to Israel, the disciples and the table, his end and his raising, and the messenger he foretold. The Qur’an calls itself a guardian over the earlier scripture (5:48), and these verses are the guardian at work: they confirm the gospels where the gospels agree with them and correct the gospels where they do not. This part gathers the verses by theme, so that each can be set beside the gospel passage it bears on, and the whole compilation stands on one page in the order of the Qur’an.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The six themes follow his life. <a href="/quran/birth/">The annunciation and the birth</a> gives the two tellings of Maryam’s story and what the Qur’an leaves out of the gospel nativities. <a href="/quran/signs/">The signs</a> lists the miracles and the phrase the Qur’an attaches to every one of them: by God’s permission. <a href="/quran/servant/">A servant and a messenger</a> sets out his titles, the denials, and the scene on the Day of Judgement in which he disowns what was said of him. <a href="/quran/table/">The table from heaven</a> is the meal the disciples asked for, with no death in it. <a href="/quran/raised/">The end of his earthly mission</a> is 4:157, the one point of flat contradiction, with the historians’ consensus stated plainly beside it. <a href="/quran/ahmad/">The good news of Aḥmad</a> is the messenger he announced, and the question of the Paraclete.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">How to read it</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Each page gives the Qur’anic text in full, with the classical commentators, and then a “Compare” section naming the gospel passages. The position on these pages is the Islamic one and is labelled as such; where the scholarly consensus runs against it, as on the crucifixion, the page says so and does not soften it. The full text of every passage, with the compilation’s headings and footnotes, is on <a href="/quran/passages/">The Qur’an on Jesus</a>, and the same passages stand inside the gospel where they fall in the story.</p>
