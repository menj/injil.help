<h2 class="wp-block-heading">How this gospel was composed</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>This gospel continues a classical practice: Muslim scholars reading, quoting and retelling the gospels through the Qur'an. In the ninth century al-Qāsim b. Ibrāhīm (d. 860) reworked Matthew's story this way. Medieval Muslim authors cite all four gospels; one survey counts more than 1,270 references across twenty writers.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>It is modelled in format and method on Ahmad Shafaat's <em>The Gospel According to Islam</em>, but its wording and structure are new.</p>
