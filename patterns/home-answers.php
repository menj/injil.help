<h3 class="wp-block-heading">Does Qur&#039;an 5:47 tell Christians to follow the four gospels?</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"ih-answer-text"} -->
<p class="ih-answer-text">No. The verse tells the people of the Injīl to judge by what God revealed in it. The Qur&#039;an names the Injīl as a revelation given to ʿĪsā (5:46), not four accounts written about him decades later by others. The command reaches the revelation within those books, which the Qur&#039;an, as guardian over them (5:48), identifies.</p>
