<h3 class="wp-block-heading">What does the Qur’an say about Jesus?</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"ih-answer-text"} -->
<p class="ih-answer-text">The Qur’an names ʿĪsā 25 times and refers to him in 93 verses. It affirms his virgin birth, his signs and his title al-Masīḥ, the Messiah. It denies that he is God or the son of God (5:116-117; 19:35), and denies that he was killed or crucified (4:157).</p>
