<h3 class="wp-block-heading">Did Paul of Tarsus and Jesus teach the same thing about the law?</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"ih-answer-text"} -->
<p class="ih-answer-text">In Matthew, Jesus says not a stroke of the law will pass away (5:18). Paul of Tarsus tells the Galatians that no one is justified by works of the law (2:16) and that Christ redeemed them from its curse (3:13). He also records his own clash with Peter over the law at Antioch (2:11-14).</p>
