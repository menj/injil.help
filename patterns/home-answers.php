<h3 class="wp-block-heading">Is a Muslim gospel a new idea?</h3>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"ih-answer-text"} -->
<p class="ih-answer-text">No. Muslim scholars have read and retold the gospels through the Qur’an for more than 1,000 years. In the ninth century al-Qāsim b. Ibrāhīm reworked the narrative of Matthew. One survey counts more than 1,270 gospel references in 20 medieval Muslim authors.</p>
