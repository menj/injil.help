<h2 class="wp-block-heading">Questions about the measure</h2>
<!-- /wp:heading -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>What does it mean to use the Qur’an as the measure?</summary><!-- wp:paragraph -->
<p>That the Qur’an decides which gospel material is the Injīl. Where the gospels agree with the Qur’an, the material is kept; where they contradict it, the material is set aside and the page says so; where the Qur’an is silent, material is kept only if critical scholarship treats it as early, and it is labelled. The Qur’an calls itself a guardian over the earlier scripture (5:48).</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Does the Qur’an confirm the Bible?</summary><!-- wp:paragraph -->
<p>It confirms the Torah and the Injīl as revelations God gave (5:44-48) and says the Prophet is described in the books with the People of the Book (7:157). It also says those books were in part altered and in part forgotten (2:79; 5:13-14). Confirming a revelation is not certifying every line of every copy of it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>What does muhaymin mean in Qur’an 5:48?</summary><!-- wp:paragraph -->
<p>Guardian, overseer, the one who watches over and judges. The Qur’an is sent down “confirming the scripture before it and as a guardian over it”. The classical commentators gloss it as witness and judge: what in the earlier books agrees with the Qur’an is confirmed, what does not is corrected.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>What is taḥrīf?</summary><!-- wp:paragraph -->
<p>Alteration. Muslim scholars distinguish alteration of meaning, reading a text against its sense, from alteration of the text itself. The Qur’an charges some of the People of the Book with both (2:79; 4:46). This website asserts textual change only where the manuscripts show it, as in Mark 16:9-20 and John 7:53-8:11.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Does this website claim the Bible was changed?</summary><!-- wp:paragraph -->
<p>It claims that the four gospels are not the Injīl given to Jesus: a question of identity, not of wholesale corruption. Within that, it names alteration of meaning where the gospels record it and alteration of text where the manuscripts show it, and it does not rest its argument on the charge that the text was replaced.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Why keep any gospel material at all?</summary><!-- wp:paragraph -->
<p>Because the Qur’an says the Injīl is in the books the Christians hold (7:157), and because the gospels preserve, among much else, a Jesus who confirmed the law, called himself a servant, and worshipped God alone. Muslim scholars have read the gospels this way since the ninth century. Discarding them would discard the Injīl with them.</p>
<!-- /wp:paragraph --></details>
