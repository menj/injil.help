<h3 class="wp-block-heading">Which claim of alteration this site makes</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The claim this website makes is one of identity, not of wholesale corruption. The Injīl the Qur'an affirms is the revelation given to ʿĪsā ibn Maryam (5:46). The four gospels are four anonymous Greek books written one to three generations after him, about him, by others. They contain material from the Injīl and material that is not from it. The measure above is how the two are told apart.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Within that claim, two kinds of alteration are named, and each only where it can be shown. Alteration of meaning (<em>taḥrīf al-maʿnā</em>) is the reading of a text against its sense: the Qur'an charges some of the People of the Book with twisting words from their places (4:46; 5:13; 5:41) and with passing off their own writing as God's (2:79), and the pages on <a href="/paul/">Paul of Tarsus</a> and on <a href="/gospels/john/">John</a> show where the gospels themselves record this happening. Alteration of text (<em>taḥrīf al-lafẓ</em>) is asserted only where the manuscripts show it: the ending of Mark (16:9-20), the woman taken in adultery (John 7:53-8:11) and the Johannine comma (1 John 5:7) are absent from the oldest witnesses and present in later ones. These are additions to a text that is otherwise copied with care, and the <a href="/gospels/discrepancies/">discrepancy tables</a> name each case. Classical Muslim scholars held both views at once and argued over their weight; the two are not an early stage and a late stage of one opinion, and this website does not present them as such.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>What follows from this is the rule stated at the top. The argument of the website does not rest on the charge that the text was replaced. It rests on the Qur'an as the measure of what in the four gospels is the Injīl, and on the gospels' own record of who wrote them, when, and against whom. Sources: Schaffner, dissertation ch. 2 (Ohio State, 2016); Tarakci and Sayar, <em>Islamic Quarterly</em> 49:3.</p>
