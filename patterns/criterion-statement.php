<h2 class="wp-block-heading">The Qur'an judges which gospel material is kept.</h2>
<!-- /wp:heading -->
<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>Where gospel material agrees with the Qur'an, this site uses it.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Where it contradicts the Qur'an, this site sets it aside and says so.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Where the Qur'an is silent, material is used only if mainstream critical scholarship treats it as early, and it is labelled as such.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Which claim of alteration this site makes</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>[State precisely: alteration of meaning (<em>taḥrīf al-maʿnā</em>), alteration of text (<em>taḥrīf al-naṣṣ</em>), or both, and for which material. Do not present the two as a simple early/late sequence; cite Schaffner ch. 2 and Tarakci &amp; Sayar, <em>Islamic Quarterly</em> 49:3.]</p>
