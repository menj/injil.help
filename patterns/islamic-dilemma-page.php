<h2 class="wp-block-heading ih-capsule-q">What is the Islamic Dilemma?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The Islamic Dilemma is a Christian apologetic argument, popularised online in the 2010s. It says the Qur&#039;an affirms the Torah and the Gospel yet contradicts them. If those books are preserved, the Qur&#039;an is wrong to contradict them; if they are corrupted, the Qur&#039;an is wrong to affirm them. Either way, it concludes, the Qur&#039;an fails.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:heading -->
<h2 class="wp-block-heading">The argument, stated fairly</h2>
<!-- /wp:heading -->
<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>The Qur&#039;an says God gave ʿĪsā the Injīl as guidance and light (5:46), and tells its people to judge by what God revealed in it (5:47).</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>The Qur&#039;an says no one can change the words of God (6:115; 18:27).</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>The four gospels teach that Jesus died on the cross and is the Son of God. The Qur&#039;an denies both (4:157; 5:116-117).</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>So either the gospels are preserved, and the Qur&#039;an contradicts scripture it affirms, or they are corrupted, and the Qur&#039;an affirms a corrupted book.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->
