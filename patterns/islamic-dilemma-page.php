<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"ih-point","layout":{"type":"default"}} -->
<div class="wp-block-group ih-point"><!-- wp:paragraph {"className":"ih-k"} -->
<p class="ih-k">Answer · II</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Confirmation is not endorsement</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p><em>Muṣaddiq</em> (confirming) is applied in the Qur’an to a message or a prophet, never to a textual canon; Jesus is said to confirm Moses (3:50; 5:46). The same verse shows that confirming is not endorsing everything: Jesus confirms the Torah and makes lawful some of what it forbade.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Q 5:48 adds that the Qur’an is <em>muhaymin</em> over the earlier books. Ibn Kathīr, on the authority of Ibn ʿAbbās and others, lists its senses as trustworthy (<em>amīn</em>), witness (<em>shāhid</em>) and dominant over every earlier scripture. Al-Ṭabarī says the Qur’an is the trustworthy custodian: whatever in the earlier books conforms to it is true, and whatever disagrees with it is false. A guardian keeps what is true and does not hand over its authority.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"ih-full"} -->
<p class="ih-full"><a href="/method/">The measure</a></p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"ih-point","layout":{"type":"default"}} -->
<div class="wp-block-group ih-point"><!-- wp:paragraph {"className":"ih-k"} -->
<p class="ih-k">Answer · III</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Taḥrīf is not the straw man</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The verb <em>yuḥarrifūna</em> occurs four times (2:75; 4:46; 5:13; 5:41), and always of Jews, never of Christians. Of Christians the Qur’an says they forgot part of what they were reminded of (5:14). Gabriel Said Reynolds argues that 4:46 is best read “they shift words out of their contexts”. Camilla Adang, surveying nine Muslim authors from Ibn Rabbān al-Ṭabarī to Ibn Ḥazm, found that the majority held that the meaning of the text had been changed and the text itself had not. Al-Ṭabarī read 2:75 as an oral distortion, and al-Rāzī argued that a text so widely recited could not have been changed wholesale.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Ryan Schaffner adds that early Muslim polemicists often made both charges together, meaning and text, with the Qur’an as the filter: biblical material was accepted when it agreed with the Qur’an and rejected as corrupted when it did not. The classical method was a discriminating one, which is not the blanket theory of textual corruption the dilemma attacks.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"ih-full"} -->
