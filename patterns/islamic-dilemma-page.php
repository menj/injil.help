<!-- wp:heading {"className":"ih-capsule-q"} -->
<h2 class="wp-block-heading ih-capsule-q">What is the Islamic Dilemma?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The Islamic Dilemma is a Christian apologetic argument that has circulated online for about two decades. It was set out on the Answering Islam website, in the writing of Sam Shamoun, and later put in syllogistic form by David Wood through Acts 17 Apologetics and Answering Muslims. It says the Qur’an affirms the Torah and the Gospel and yet contradicts them. If the Bible is corrupt, the Qur’an affirms a corrupt scripture; if it is sound, its doctrines refute Islam. Either way, it concludes, Islam is caught.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Where the argument came from</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Its modern home is Answering Islam, where Sam Shamoun’s articles on the Qur’an’s witness to the Bible and on <em>taḥrīf</em> (corruption) make the case, and the circle around David Wood, Acts 17 Apologetics and the late Nabeel Qureshi carried it into video. The argument is older than its name. Karl Pfander’s <em>Mīzān al-Ḥaqq</em> (“The Balance of Truth”, drafted in German in 1829 and printed in Persian in the 1830s) reasoned from the Qur’an’s respect for the earlier scriptures to the duty of Muslims to accept them. A letter of 1732 by the Christian writer Isṭifān Ward, known only in summary, argues that Qur’an 3:84, 5:46 and 2:87 attest the authenticity of the Torah and Gospel, which is the first horn of the dilemma almost three centuries before Shamoun and Wood.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">The argument, stated fairly</h2>
<!-- /wp:heading -->
<!-- wp:list {"ordered":true} -->
<ol class="wp-block-list"><!-- wp:list-item -->
<li>The Qur’an confirms the Torah and the Gospel (3:3; 5:46).</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>The Torah and the Gospel are the Bible that Jews and Christians hold today, and the four gospels in particular.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>That Bible teaches what Islam rejects: the crucifixion, the divine sonship of Jesus, the Trinity, and salvation through him (4:157; 5:116-117).</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>So if Muslims affirm that Bible, Islam contradicts itself; and if they deny it, the Qur’an has confirmed a corrupted book.</li>
<!-- /wp:list-item --></ol>
<!-- /wp:list -->
<!-- wp:paragraph -->
<p>The force of the argument depends on four substitutions that are rarely stated. “Gospel” is made to mean the fourfold New Testament canon. “Torah” is made to mean the whole received Old Testament. “Confirmation” is made to mean endorsement of the text word for word. And “the People of the Book” are made to possess one stable Bible, identical to a later Protestant, Catholic or critical edition. Once the four substitutions are named, the dilemma becomes a chain of contested assumptions. The study answers it in three parts, then adds two considerations the argument leaves out.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Why the Islamic Dilemma fails</h2>
<!-- /wp:heading -->
<!-- wp:group {"className":"ih-points","layout":{"type":"default"}} -->
<div class="wp-block-group ih-points"><!-- wp:group {"className":"ih-point","layout":{"type":"default"}} -->
<div class="wp-block-group ih-point"><!-- wp:paragraph {"className":"ih-k"} -->
<p class="ih-k">Answer · I</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">The Qur’anic Injīl is not the New Testament</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Every Qur’anic use of <em>al-Injīl</em> is singular, as Sidney Griffith notes; the plural <em>anājīl</em> never occurs. It is a revelation given to ʿĪsā, as the Torah was given to Mūsā (5:46). <em>Al-Tawrāh</em> is likewise always singular. Neither names a multi-book canon.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>There was also no single Bible for the Qur’an’s first audience to confirm. Tatian’s harmony of the four gospels, not the separate four, was the dominant gospel in the Syriac world of the late seventh century, on Griffith’s evidence. The Syriac New Testament of the Church of the East, the Peshitta, had twenty-two books, without 2 Peter, 2 and 3 John, Jude and Revelation. And Irenaeus, about 180 CE, is the first Christian to argue formally for four gospels, against those who held to one. The prior question is always which Bible, in which language, with which canon.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"ih-full"} -->
