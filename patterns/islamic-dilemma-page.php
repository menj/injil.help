<p class="ih-k">Answer · VI</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Muslims have always read the gospels this way</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Medieval Muslim scholars quoted the gospels and sorted what agreed with the Qur’an from what did not. The Prophet’s own instruction, recorded in al-Bukhārī (7362), was “do not believe the People of the Book and do not disbelieve them, but say: we believe in God and in what was revealed to us”. Ibn Ḥajar reads it as reserve, with the Qur’an as the criterion. In the fifteenth century Ibrāhīm al-Biqāʿī defended the use of the Bible in commentary, against a rival who accused him of glorifying it, and said that the Qur’an, the Prophet, the Companions and the scholars of every age had referred to the earlier scriptures. The Gospel According to Islam on this website continues that practice.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"ih-full"} -->
<p class="ih-full"><a href="/gospel-according-to-islam/">The Gospel According to Islam</a></p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->
<!-- wp:heading -->
<h2 class="wp-block-heading">How the verses work</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The dilemma reads the verses on earlier scripture as free-standing statements that the Bible is divinely vouched for. They are arguments. They address specific Jewish and Christian communities in the Ḥijāz and Medina, and hold them to their own scripture: if they truly revered what they were given, they would recognise its continuity with what is now sent to Muḥammad (5:43-48, 68). Where those verses use confirmation to settle a point for listeners who had never heard the stories of Moses and Jesus, they tell them that these stories stand in continuity with revelation their neighbours already accepted.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The Qur’an speaks across four registers, which the dilemma collapses into one:</p>
<!-- /wp:paragraph -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>Original revelation</strong>: affirmed, as given to Moses and Jesus.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>Historical transmission</strong>: criticised, as handled by the communities entrusted with it (5:44; 5:14).</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>Communal canon</strong>: never identified with the original, and never named.</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li><strong>Continuing authority</strong>: held by the Qur’an as <em>muhaymin</em> (5:48).</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->
<!-- wp:paragraph -->
<p>Jesus himself offers a parallel in the first gospel. He tells his disciples that the Pharisees sit in Moses’ seat and that they should do “all” that they say (Matthew 23:1-3), and then condemns specific Pharisaic teachings in the same chapter. Christian readers rightly take “all” with care. The same care applies to “uphold the Torah and the Gospel”.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>A note on method. The study observes that Answering Islam applies textual criticism one way: it questions the Bible’s alleged predictions of Muḥammad (Deuteronomy 18:18; John 14-16) from the manuscripts, yet treats the manuscripts behind the Trinitarian and Christological proof-texts (1 John 5:7-8; 1 Timothy 3:16; John 1:18; Hebrews 2:9) as settled. It also sets the gospels’ “eyewitness” character against the Qur’an, though the gospels are anonymous and Mark is dated about 35 to 45 years after the events. Christians read the Old Testament by a later revelation as criterion, treating the dietary laws and the temple cult as superseded, and that is the structure of the Muslim reading of both earlier scriptures. Either both traditions may arbitrate earlier scripture, or neither.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">Objection and reply</h2>
<!-- /wp:heading -->
<!-- wp:group {"align":"wide","className":"is-style-objection-reply","layout":{"type":"default"}} -->
<div class="wp-block-group alignwide is-style-objection-reply"><!-- wp:group {"layout":{"type":"default"}} -->
<div class="wp-block-group"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Objection</h4>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The Qur’an tells the people of the Injīl to judge by it (5:47). The Christians of the seventh century held the four gospels. If the Injīl was not those books, what did they hold, and how could the Qur’an send them to it?</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --><!-- wp:group {"layout":{"type":"default"}} -->
<div class="wp-block-group"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Best Christian reply</h4>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The strongest reply says that “the Injīl” can only mean the gospel scriptures the church possessed, since the Qur’an calls Christians “the people of the Injīl” and tells them to judge by it. A command to follow a book presupposes that the book is sound. This is the reasoning of Pfander’s <em>Mīzān al-Ḥaqq</em>, and it is the form the dilemma takes on Answering Islam and in the videos of David Wood.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group --><!-- wp:group {"layout":{"type":"default"}} -->
<div class="wp-block-group"><!-- wp:heading {"level":4} -->
<h4 class="wp-block-heading">Response</h4>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The verse commands them to judge by “what God revealed in it” (<em>bimā anzala fīhi</em>), which leaves open which contents of the Christian canon are revelation, and 5:48 at once makes the Qur’an <em>muhaymin</em> over them. Al-Ṭabarī reads that as: whatever in the earlier books agrees with the Qur’an is true, and whatever disagrees is false. The Injīl is the revelation given to ʿĪsā, which the canonical gospels, the harmonised tradition, the Jewish-Christian gospel material and the oral tradition each preserve in part. The study calls it a theological category, the heavenly archetype of that revelation, and says that asking where the lost book is presupposes a position Muslims do not hold.</p>
