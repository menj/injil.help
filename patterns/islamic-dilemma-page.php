<p class="ih-k">Answer · IV</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">The Bible’s own textual history</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The Dead Sea Scrolls show that before 70 CE the Hebrew Bible existed in several forms side by side, and Emanuel Tov concludes that the Masoretic Text should no longer sit at the centre of textual thinking. In the New Testament, every modern critical edition judges the Comma Johanneum (1 John 5:7-8) spurious, the story of the woman caught in adultery (John 7:53-8:11) is absent from the earliest Greek witnesses, and Codex Sinaiticus and Codex Vaticanus end Mark at 16:8. Bruce Metzger notes that no uncial manuscript in its original hand before the eighth or ninth century supports the reading “God” at 1 Timothy 3:16.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>None of this is a Muslim claim. It is the finding of mainstream textual criticism, and it fits the classical doctrine of <em>taḥrīf</em>. It does not fit the assumption that the Bible Christians held in 1480, 1611 or today is textually identical to the revelations the Qur’an affirms.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"ih-full"} -->
<p class="ih-full"><a href="/gospels/discrepancies/">The discrepancy tables</a></p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"ih-point","layout":{"type":"default"}} -->
<div class="wp-block-group ih-point"><!-- wp:paragraph {"className":"ih-k"} -->
<p class="ih-k">Answer · V</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Paul stands outside, and the canon is not of one mind</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Fourteen of the New Testament’s twenty-seven documents are attributed to Paul of Tarsus or, in the case of Hebrews, were placed under his name, and Islam does not recognise Paul as a prophet. Islamic theology holds, on reports in al-Bukhārī and Muslim, that no prophet came between ʿĪsā and Muḥammad, and Paul claims a commission from the risen Christ. The Qur’anic <em>ḥawāriyyūn</em> (3:52; 5:111-112; 61:14) were the companions of Jesus in his lifetime, a category Paul by his own account does not fill. The command at 5:47 concerns the revelation given to Jesus, and Paul’s letters, written decades later, are a separate body of writing.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The canon is also divided on the doctrines the dilemma turns on. Hebrews says that without the shedding of blood there is no forgiveness (9:22). Psalm 51:16-17, Hosea 6:6 and Ezekiel 18 speak of forgiveness through a broken heart, mercy and repentance. And the Qur’an attributes to the scrolls of Abraham and Moses the principle that no bearer of burdens bears another’s burden (53:36-38). The argument grants the Bible a harmonising reading in advance and denies the Qur’an the same.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"ih-full"} -->
