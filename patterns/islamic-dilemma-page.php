<h2 class="wp-block-heading">Questions about the Islamic Dilemma</h2>
<!-- /wp:heading -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Who started the Islamic Dilemma?</summary><!-- wp:paragraph -->
<p>The study traces its modern form to Sam Shamoun’s writing on Answering Islam, and its syllogistic form to David Wood at Acts 17 Apologetics and Answering Muslims. Older forms of the first horn are found in Karl Pfander’s <em>Mīzān al-Ḥaqq</em> and in Isṭifān Ward’s letter of 1732. A dilemma of the same shape was pressed against Christianity itself by the pagan critics Celsus and Julian, as Robert Wilken records, before it was turned on Islam.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Does Qur’an 6:115 or 18:27 mean the Bible cannot be corrupted?</summary><!-- wp:paragraph -->
<p>No. “None can change His words” (6:115; 18:27) is read by al-Ṭabarī, al-Rāzī and Ibn Kathīr of God’s decrees, promises and judgements, or of the Qur’an itself; 18:27 opens with an instruction to the Prophet about the Qur’an. Neither verse is a guarantee for the manuscripts of earlier scriptures, which the Qur’an elsewhere says some altered (2:75; 4:46; 5:13). The Qur’an itself draws the line between earlier custody by people (5:44) and its own divine guarding (15:9).</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Does Qur’an 5:47 tell Christians to follow the four gospels?</summary><!-- wp:paragraph -->
<p>No. The verse tells the people of the Injīl to judge by what God revealed in it. The Qur’an names the Injīl as a revelation given to ʿĪsā (5:46), not four accounts written about him decades later by others. The command reaches the revelation within those books, which the Qur’an, as guardian over them (5:48), identifies.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Does Qur’an 10:94, “ask those who recite the Book before you”, make the Bible reliable?</summary><!-- wp:paragraph -->
<p>No. Al-Ṭabarī and al-Rāzī read the address as rhetorical: the Prophet was free of doubt, and the condition is for any hearer who might doubt. The earliest commentators identify the people to ask as former Jews and Christians who had accepted Islam, such as ʿAbdullāh ibn Salām and Salmān al-Fārisī, whose reading of their own scriptures had led them to it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Does Qur’an 3:84, “we make no distinction between any of them”, forbid calling the Bible corrupt?</summary><!-- wp:paragraph -->
<p>No. The antecedent is persons, the prophets, not their texts. <em>Tafrīq</em> in the Qur’an is accepting some messengers and rejecting others (2:285; 4:150-152). A Muslim who rejects a doctrine later attributed to Jesus rejects the accretion and keeps the messenger.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Does Qur’an 5:68, “uphold the Torah, the Gospel”, bind Muslims to the present Bible?</summary><!-- wp:paragraph -->
<p>No. The verse is addressed to the People of the Book in their own time and calls them to consistency with the revelation given to them. It goes on to say that what is sent down to Muḥammad will increase many of them in transgression, which presupposes a tension between the genuine revelation and the tradition built on it.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Is it circular for Muslims to accept what agrees with the Qur’an and reject the rest?</summary><!-- wp:paragraph -->
<p>Every later revelation works this way. Christians read the Hebrew scriptures through Christ, treating the dietary laws as abrogated and the priesthood and temple as fulfilled. The study argues that this is the same method as the Muslim reading of both earlier scriptures, so that the charge of circularity either falls on both or on neither.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details {"className":"is-style-faq"} -->
<details class="wp-block-details is-style-faq"><summary>Where is the Injīl, if it is not the four gospels?</summary><!-- wp:paragraph -->
<p>It was never a book that Muslims say survives on a shelf. It is the revelation given to ʿĪsā, which the canonical gospels, Tatian’s harmony, the Jewish-Christian gospels and the oral tradition behind them each preserve in part. The Jewish-Christian gospels, known from Jerome, Epiphanius and Origen, are fragmentary and are not to be identified directly with the Injīl, though they show that early devotion to Jesus was more varied than the later canon suggests.</p>
