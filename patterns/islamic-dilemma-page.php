<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Confirming is not certifying every word</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>The Qur&#039;an calls itself muṣaddiq, confirming, and muhaymin, guardian, over the scripture before it (5:48). A guardian keeps what is true and rejects what is not. The dilemma reads “confirm” as “endorse in full”, which the verse does not say.</p>
