<h2 class="wp-block-heading">Do the resurrection accounts agree?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"ih-answer-text"} -->
<p class="ih-answer-text">They agree that the tomb was empty on the first day of the week. They disagree on who went, who was waiting there, what the women did next, and whether the disciples first saw Jesus in Galilee or in Jerusalem. The earliest manuscripts of Mark end with no appearance at all.</p>
