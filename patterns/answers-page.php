<h2 class="wp-block-heading">Did Jesus claim to be God?</h2>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"ih-answer-text"} -->
<p class="ih-answer-text">Not in Mark, Matthew or Luke. There he prays to God, asks why anyone calls him good when God alone is good (Mark 10:18), and says only the Father knows the hour (Mark 13:32). The plain claims appear in John, the latest gospel, which most critical scholars do not read as a record of his words.</p>
