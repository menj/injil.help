<h2 class="wp-block-heading">What this part holds</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Everything on this website that is not argument is here: the tools a reader needs to check the argument, and the record of how the argument has been tested. None of it is decoration. The <a href="/resources/timeline/">timeline</a> sets every gospel, letter, council and manuscript on one line from the birth of Jesus to the Qur’an, so that the distance between an event and its earliest record can be seen at a glance. The <a href="/resources/glossary/">glossary</a> defines the Arabic, Greek, Hebrew and Syriac terms and the vocabulary of New Testament scholarship that the articles use without stopping to explain. The <a href="/resources/sources/">source library</a> indexes every work cited, by kind, with the pages that lean on it.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>The second half is the website answering for itself. The <a href="/answers/">FAQs</a> give the questions people search for most, each answered in under sixty words and linked to the page with the evidence. <a href="/resources/objections/">Objections and replies</a> states the strongest Christian objections to this website’s case, in the form a Christian apologist would accept, and answers each. <a href="/resources/responses/">Responses to named articles</a> does the same for four published articles, claim by claim. The <a href="/corrections/">corrections log</a> records every error found on the website, with what the page said and what it now says, so that a reader can see the website has been wrong and how it put the matter right.</p>
<!-- /wp:paragraph -->
<!-- wp:heading -->
<h2 class="wp-block-heading">How to use it</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Read the articles with the glossary and the timeline open; every date and term in them is here. If an article’s source list names a work, the source library gives its edition and the other pages that use it. If you think an article is wrong, the <a href="/contact/">contact page</a> says how to report it and what a useful report contains. If you are a Christian reader with a reply, the objections and responses pages are where the best replies are published and answered, and a good one will end up there.</p>
